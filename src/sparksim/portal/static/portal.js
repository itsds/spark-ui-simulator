// Scenario portal: run status polling, progressive hints, notes and the solution reveal.
// Progress (hints shown, notes, solution) is kept per scenario in this browser's localStorage.
(function () {
  "use strict";

  const store = {
    get(key, fallback) {
      try { const v = localStorage.getItem(key); return v === null ? fallback : v; } catch (e) { return fallback; }
    },
    set(key, value) { try { localStorage.setItem(key, value); } catch (e) { /* private window: no persistence */ } },
    del(key) { try { localStorage.removeItem(key); } catch (e) { /* ignore */ } },
  };

  // ------------------------------------------------------------------ status of the runs and the services

  function noteFor(app, info, scenarios) {
    if (info.state === "missing") {
      return "Not generated yet. Run: uv run sparksim prepare " + scenarios.join(" ");
    }
    if (info.state === "hs-down") {
      return "Start the stack with: uv run sparksim up (or docker compose up).";
    }
    if (info.state === "loading") {
      return "The History Server rescans its log directory every 5 s; large logs take a few seconds more.";
    }
    if (info.stale && (info.state === "ready" || info.state === "loading")) {
      return "Generated by an older version of this scenario or of the simulator: uv run sparksim prepare regenerates it.";
    }
    return "";
  }

  function applyStatus(st) {
    for (const [svc, info] of Object.entries({ history_server: st.history_server, nm_logs: st.nm_logs })) {
      document.querySelectorAll('.svc[data-svc="' + svc + '"]').forEach((el) => {
        el.dataset.up = String(!!info.up);
        el.title = info.up ? "running" : "not reachable";
      });
    }
    let pending = false;
    document.querySelectorAll(".state[data-app]").forEach((el) => {
      const info = st.apps[el.dataset.app];
      if (!info) { el.dataset.state = "unknown"; el.textContent = "Unknown"; return; }
      el.dataset.state = info.state;
      el.textContent = info.text + (info.state === "ready" && info.stale ? " (out of date)" : "");
      if (info.state !== "ready") pending = true;
    });
    document.querySelectorAll(".run[data-run]").forEach((run) => {
      const app = run.dataset.run;
      const info = st.apps[app];
      if (!info) return;
      run.dataset.ready = String(info.state === "ready");
      run.querySelectorAll(".hs-links a[data-page]").forEach((a) => {
        a.href = st.history_server.url.replace(/\/$/, "") + "/history/" + app + "/" + info.attempt + "/" + a.dataset.page;
      });
      const note = run.querySelector(".run-note");
      const text = noteFor(app, info, info.scenarios);
      note.textContent = text;
      note.hidden = !text;
    });
    return pending;
  }

  function poll() {
    fetch("/api/status", { cache: "no-store" })
      .then((r) => r.json())
      .then((st) => setTimeout(poll, applyStatus(st) ? 3000 : 15000))
      .catch(() => setTimeout(poll, 5000));
  }
  if (document.querySelector(".state[data-app], .svc")) poll();

  // ------------------------------------------------------------------ scenario page

  const layout = document.querySelector(".layout[data-scenario]");
  if (!layout) return;
  const id = layout.dataset.scenario;
  const key = (k) => "sparksim:" + id + ":" + k;

  // hints, one at a time
  const hintsBox = document.getElementById("hints");
  const hints = hintsBox ? Array.from(hintsBox.querySelectorAll(".hint")) : [];
  const nextBtn = hintsBox && hintsBox.querySelector('[data-action="next-hint"]');
  const hideBtn = hintsBox && hintsBox.querySelector('[data-action="hide-hints"]');
  function showHints(n, scroll) {
    n = Math.max(0, Math.min(n, hints.length));
    hints.forEach((h, i) => { h.hidden = i >= n; });
    if (nextBtn) {
      nextBtn.hidden = n >= hints.length;
      nextBtn.textContent = "Show hint " + (n + 1) + " of " + hints.length;
    }
    if (hideBtn) hideBtn.hidden = n === 0;
    store.set(key("hints"), String(n));
    if (scroll && n > 0) hints[n - 1].scrollIntoView({ behavior: "smooth", block: "nearest" });
  }
  if (hints.length) {
    showHints(parseInt(store.get(key("hints"), "0"), 10) || 0, false);
    nextBtn.addEventListener("click", () => showHints((parseInt(store.get(key("hints"), "0"), 10) || 0) + 1, true));
    hideBtn.addEventListener("click", () => showHints(0, false));
  }

  // notes
  const notes = document.querySelector("#notes textarea");
  const saved = document.querySelector("#notes .saved");
  let timer = null;
  notes.value = store.get(key("notes"), "");
  notes.addEventListener("input", () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      store.set(key("notes"), notes.value);
      saved.textContent = "Saved in this browser.";
    }, 400);
  });

  // solution: a second click confirms when no diagnosis is written yet
  const sol = document.getElementById("solution");
  const revealBtn = sol && sol.querySelector('[data-action="reveal-solution"]');
  const hideSolBtn = sol && sol.querySelector('[data-action="hide-solution"]');
  const solBody = sol && sol.querySelector(".solution-body");
  function showSolution(on) {
    solBody.hidden = !on;
    revealBtn.hidden = on;
    hideSolBtn.hidden = !on;
    revealBtn.textContent = "Reveal the solution";
    delete revealBtn.dataset.armed;
    if (on) store.set(key("solution"), "1"); else store.del(key("solution"));
  }
  if (sol) {
    showSolution(store.get(key("solution"), "") === "1");
    revealBtn.addEventListener("click", () => {
      if (!notes.value.trim() && !revealBtn.dataset.armed) {
        revealBtn.dataset.armed = "1";
        revealBtn.textContent = "No diagnosis written yet. Click again to reveal anyway";
        return;
      }
      showSolution(true);
      sol.scrollIntoView({ behavior: "smooth", block: "start" });
    });
    hideSolBtn.addEventListener("click", () => showSolution(false));
  }

  // reset (a second click confirms when it would delete notes)
  const resetBtn = document.querySelector('[data-action="reset"]');
  const resetText = resetBtn.textContent;
  resetBtn.addEventListener("click", () => {
    if (notes.value.trim() && !resetBtn.dataset.armed) {
      resetBtn.dataset.armed = "1";
      resetBtn.textContent = "This deletes your notes. Click again to reset";
      return;
    }
    delete resetBtn.dataset.armed;
    resetBtn.textContent = resetText;
    store.del(key("notes"));
    notes.value = "";
    saved.textContent = "";
    if (hints.length) showHints(0, false);
    if (sol) showSolution(false);
  });
})();
