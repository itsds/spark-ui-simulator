"""Keep generated outputs up to date with their scenarios: `sparksim prepare` (and `sparksim generate`).

Each run of a scenario is one application, `application_<clusterTs>_<seq>`. What decides its bytes is the
job and the run in `scenario.yaml` (the run's label excluded) and the simulator's code: their hash is the
app's *fingerprint*. `<event-logs>/.sparksim-manifest.json` records the fingerprint each event log was
generated with (a hidden file: the History Server skips it, ADR-032), plus what a running `prepare` is
doing, which the portal shows. `prepare` regenerates only apps whose event log, container logs or
fingerprint is missing or different. Scenarios that share a run share its app (Scenario 01's last good run
is Scenario 00's run): it is generated once, and two different runs may not claim the same app id.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import time
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from datetime import UTC, datetime
from functools import cache
from pathlib import Path

from .scenario import Scenario, load_scenario, scenario_ids

MANIFEST = ".sparksim-manifest.json"
# Package parts that don't change a generated byte: editing the portal must not trigger a regeneration.
_NOT_SIMULATION = {"portal", "cli.py", "prepare.py", "up.py", "__pycache__"}
# A `prepare` that hasn't written its progress for this long has died (one app takes ~15 s).
STALE_PROGRESS_S = 15 * 60


@cache
def code_fingerprint() -> str:
    """sha256 of the simulator's source (every file of the package outside `_NOT_SIMULATION`)."""
    pkg = Path(__file__).resolve().parent
    h = hashlib.sha256()
    for p in sorted(pkg.rglob("*")):
        rel = p.relative_to(pkg)
        if not p.is_file() or rel.parts[0] in _NOT_SIMULATION or "__pycache__" in rel.parts or p.suffix == ".pyc":
            continue
        h.update(rel.as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()


def run_definition(sc: Scenario, role: str) -> str:
    """The job and the run as canonical JSON: everything in scenario.yaml that changes the app's bytes."""
    run = sc.model.runs[role].model_dump(mode="json", exclude={"label"})
    return json.dumps({"job": sc.model.job.model_dump(mode="json"), "run": run}, sort_keys=True)


def app_fingerprint(sc: Scenario, role: str) -> str:
    h = hashlib.sha256(run_definition(sc, role).encode())
    h.update(code_fingerprint().encode())
    return h.hexdigest()[:24]


@dataclass
class AppPlan:
    """One application to have on disk, and every (scenario, run role) that uses it."""

    app_id: str
    fingerprint: str
    uses: list[tuple[Scenario, str]] = field(default_factory=list)

    @property
    def event_log_name(self) -> str:
        return f"{self.app_id}_1"  # YARN cluster mode: attempt 1

    @property
    def scenario_ids(self) -> list[str]:
        return sorted({sc.id for sc, _ in self.uses})


def plan_apps(scenarios: Iterable[Scenario]) -> list[AppPlan]:
    """The apps the scenarios' runs need, in scenario order; a run shared by scenarios is one app.

    Raises ValueError when two different runs claim the same app id (their logs would overwrite each other)."""
    plans: dict[str, AppPlan] = {}
    for sc in scenarios:
        for role in sc.roles:
            app = sc.app_id(role)
            fp = app_fingerprint(sc, role)
            p = plans.get(app)
            if p is None:
                plans[app] = AppPlan(app, fp, [(sc, role)])
                continue
            if p.fingerprint != fp:
                other, other_role = p.uses[0]
                raise ValueError(
                    f"{app} is claimed by two different runs: {other.id} ({other_role}) and {sc.id} ({role}). "
                    "Runs may share an app id only when their job and run are identical; give one a new app_seq.")
            p.uses.append((sc, role))
    return list(plans.values())


# ---------------------------------------------------------------------------- the manifest


def _now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


@dataclass
class Manifest:
    """`<event-logs>/.sparksim-manifest.json`: which fingerprint each log has, and a running prepare's progress."""

    path: Path
    apps: dict[str, dict] = field(default_factory=dict)
    progress: dict | None = None  # {"pending": [app ids], "generating": app id | None, "updated": epoch s}

    @classmethod
    def load(cls, event_logs: str | Path) -> Manifest:
        path = Path(event_logs) / MANIFEST
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            raw = {}
        return cls(path, raw.get("apps", {}), raw.get("progress"))

    def save(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_name(self.path.name + ".tmp")
        tmp.write_text(json.dumps({"version": 1, "apps": self.apps, "progress": self.progress}, indent=1,
                                  sort_keys=True) + "\n", encoding="utf-8")
        os.replace(tmp, self.path)

    def record(self, app_id: str, fingerprint: str, scenarios: list[str], event_log: str) -> None:
        self.apps[app_id] = {"fingerprint": fingerprint, "scenarios": scenarios, "event_log": event_log,
                             "generated_at": _now()}

    def active_progress(self) -> dict | None:
        """The progress of a prepare that is still running (not one that died half-way)."""
        p = self.progress
        if not p or time.time() - p.get("updated", 0) > STALE_PROGRESS_S:
            return None
        return p


def app_state(plan: AppPlan, event_logs: Path, yarn_logs: Path | None, manifest: Manifest) -> str:
    """`fresh`, `missing` (no event log or container logs) or `stale` (generated from another fingerprint)."""
    if not (event_logs / plan.event_log_name).is_file():
        return "missing"
    if yarn_logs is not None and not (yarn_logs / plan.app_id).is_dir():
        return "missing"
    rec = manifest.apps.get(plan.app_id)
    return "fresh" if rec and rec.get("fingerprint") == plan.fingerprint else "stale"


# ---------------------------------------------------------------------------- generation


def generate_app(sc: Scenario, role: str, event_logs: str | Path, yarn_logs: str | Path | None,
                 seed: int | None = None, manifest: Manifest | None = None) -> Path:
    """Simulate one run and write its container logs, then its event log (atomically: the History Server
    lists the app only once its container logs exist); record it in the manifest. A `seed` override
    makes a run that is not the scenario's: it gets no fingerprint, so `prepare` regenerates it."""
    from dataclasses import replace

    from .engine.emit import build_events
    from .engine.runtime import AppRun
    from .eventlog import write_event_log
    from .yarnlogs import write_container_logs

    event_logs = Path(event_logs)
    spec = sc.spec(role)
    if seed is not None:
        spec = replace(spec, seed=seed)
    run = AppRun(spec).run()
    if yarn_logs is not None:
        shutil.rmtree(Path(yarn_logs) / run.yapp.app_id, ignore_errors=True)  # no containers of an older version
        write_container_logs(run, yarn_logs)
    path = write_event_log(event_logs / run.yapp.event_log_name, build_events(run))
    m = manifest or Manifest.load(event_logs)
    if seed is None:
        m.record(run.yapp.app_id, app_fingerprint(sc, role), [sc.id], path.name)
    else:
        m.apps.pop(run.yapp.app_id, None)
    m.save()
    return path


def prepare(scenarios: Iterable[str | Scenario] | None, event_logs: str | Path, yarn_logs: str | Path | None,
            force: bool = False, log: Callable[[str], None] = print) -> list[tuple[str, str]]:
    """Generate every app the scenarios need whose outputs are missing or stale; return (app id, action)."""
    scs = [s if isinstance(s, Scenario) else load_scenario(s) for s in (scenarios or scenario_ids())]
    event_logs = Path(event_logs)
    yarn_logs = Path(yarn_logs) if yarn_logs is not None else None
    plans = plan_apps(scs)
    m = Manifest.load(event_logs)
    todo = [p for p in plans if force or app_state(p, event_logs, yarn_logs, m) != "fresh"]
    done: list[tuple[str, str]] = []
    for p in plans:
        if p not in todo:
            m.apps[p.app_id]["scenarios"] = p.scenario_ids
            log(f"up to date  {p.app_id}  ({', '.join(p.scenario_ids)})")
            done.append((p.app_id, "up to date"))
    try:
        for i, p in enumerate(todo):
            m.progress = {"pending": [q.app_id for q in todo[i:]], "generating": p.app_id, "updated": time.time()}
            m.save()
            sc, role = p.uses[0]
            log(f"generating  {p.app_id}  ({', '.join(p.scenario_ids)}: {sc.model.runs[role].label}) ...")
            t0 = time.monotonic()
            generate_app(sc, role, event_logs, yarn_logs, manifest=m)
            m.apps[p.app_id]["scenarios"] = p.scenario_ids
            log(f"            done in {time.monotonic() - t0:.0f} s")
            done.append((p.app_id, "generated"))
    finally:
        m.progress = None
        m.save()
    return done
