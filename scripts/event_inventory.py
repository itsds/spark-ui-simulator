#!/usr/bin/env python3
"""Infer the schema of every Spark event type from real event logs.

Writes docs/event-log-schema.md: per event type, which reference apps emit it,
how often, and the merged field tree with JSON types and an example value.
This is the field-level contract the event-log writer (Phase 2) must satisfy.

  uv run scripts/event_inventory.py                 # reads reference/event-logs/*
  uv run scripts/event_inventory.py --out -         # print to stdout
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class Node:
    """Merged structure of all values seen at one JSON path."""

    def __init__(self):
        self.types: Counter = Counter()
        self.children: dict[str, Node] = {}
        self.items: Node | None = None
        self.example = None

    def add(self, v):
        t = type(v).__name__ if v is not None else "null"
        t = {"str": "string", "dict": "object", "list": "array"}.get(t, t)
        self.types[t] += 1
        if isinstance(v, dict):
            for k, cv in v.items():
                self.children.setdefault(k, Node()).add(cv)
        elif isinstance(v, list):
            for item in v:
                if self.items is None:
                    self.items = Node()
                self.items.add(item)
        elif self.example is None and v is not None:
            self.example = v

    def render(self, name: str, depth: int, out: list[str], max_depth: int = 6):
        types = "|".join(t for t, _ in self.types.most_common())
        ex = ""
        if self.example is not None:
            s = json.dumps(self.example)
            ex = f" e.g. `{s[:70] + '…' if len(s) > 70 else s}`".replace("|", "\\|")
        out.append(f"{'  ' * depth}- **{name}**: {types}{ex}")
        if depth >= max_depth:
            return
        for k in self.children:
            self.children[k].render(k, depth + 1, out, max_depth)
        if self.items is not None:
            self.items.render("[]", depth + 1, out, max_depth)


# Keys whose children are data-dependent names (property names, metric names...),
# so listing every key is noise. We collapse them to a single "<key>" child.
DYNAMIC_KEY_PARENTS = {
    "Spark Properties", "Hadoop Properties", "System Properties", "Classpath Entries", "Metrics Properties",
    "JVM Information", "Executor Resource Requests", "Task Resource Requests", "Executor Metrics Updated",
    "Task Executor Metrics", "Executor Metrics", "Log Urls", "Attributes", "Resources",
}


def collapse(v, parent: str | None = None):
    if isinstance(v, dict):
        if parent in DYNAMIC_KEY_PARENTS and v:
            first = next(iter(v.values()))
            return {"<key>": collapse(first)}
        return {k: collapse(cv, k) for k, cv in v.items()}
    if isinstance(v, list):
        return [collapse(x, parent) for x in v]
    return v


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--logs", type=Path, default=ROOT / "reference" / "event-logs")
    ap.add_argument("--out", default=str(ROOT / "docs" / "event-log-schema.md"))
    a = ap.parse_args(argv)

    trees: dict[str, Node] = defaultdict(Node)
    per_app: dict[str, Counter] = {}
    order: list[str] = []
    for f in sorted(p for p in a.logs.iterdir() if p.is_file()):
        c = Counter()
        for line in f.open():
            if not line.strip():
                continue
            e = json.loads(line)
            name = e["Event"]
            if name not in trees:
                order.append(name)
            c[name] += 1
            trees[name].add(collapse(e))
        per_app[f.name] = c

    apps = list(per_app)
    out = [
        "# Spark 3.5.9 event-log schema (generated)",
        "",
        "Generated by `scripts/event_inventory.py` from `reference/event-logs/` — do not edit by hand.",
        "Interpretation and UI mapping live in `EVENT_LOG_FORMAT.md`.",
        "",
        "## Event counts per reference app",
        "",
        "| Event | " + " | ".join(a.split("-", 1)[0] for a in apps) + " |",
        "|---|" + "---|" * len(apps),
    ]
    for name in order:
        short = name.rsplit(".", 1)[-1]
        out.append(f"| `{short}` | " + " | ".join(str(per_app[a][name] or "") for a in apps) + " |")
    out += ["", "Apps: " + ", ".join(f"`{a}`" for a in apps), "", "## Field trees", ""]
    for name in order:
        out += [f"### `{name}`", ""]
        lines: list[str] = []
        root = trees[name]
        for k, child in root.children.items():
            child.render(k, 0, lines)
        out += lines + [""]

    text = "\n".join(out) + "\n"
    if a.out == "-":
        print(text)
    else:
        Path(a.out).write_text(text)
        print(f"wrote {a.out} ({len(order)} event types, {len(apps)} apps)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
